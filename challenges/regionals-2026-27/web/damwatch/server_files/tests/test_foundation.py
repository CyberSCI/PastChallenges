import pytest
from fastapi.testclient import TestClient

from server_files.app import create_app
from server_files.config import load_settings_from_env


def test_settings_require_three_distinct_nonempty_flags(monkeypatch):
    monkeypatch.setenv("DAMWATCH_FLAG_1", "test-one")
    monkeypatch.setenv("DAMWATCH_FLAG_2", "test-two")
    monkeypatch.setenv("DAMWATCH_FLAG_3", "test-two")
    monkeypatch.setenv("DAMWATCH_PUBLIC_ORIGIN", "https://damwatch.test")

    with pytest.raises(ValueError, match="distinct"):
        load_settings_from_env()

    monkeypatch.setenv("DAMWATCH_FLAG_3", "test-three")
    assert load_settings_from_env().flag_3 == "test-three"

    monkeypatch.delenv("DAMWATCH_FLAG_1")
    with pytest.raises(ValueError, match="DAMWATCH_FLAG_1"):
        load_settings_from_env()


def test_healthz_has_no_cookie_or_flags(settings):
    with TestClient(create_app(settings), base_url="https://damwatch.test") as client:
        response = client.get("/healthz")

    assert response.status_code == 200
    assert response.json() == {"status": "ok"}
    assert "set-cookie" not in response.headers
    assert all(
        flag not in response.text for flag in ("test-one", "test-two", "test-three")
    )


def test_autogenerated_api_docs_are_not_exposed(settings):
    with TestClient(create_app(settings), base_url="https://damwatch.test") as client:
        responses = [client.get(path) for path in ("/docs", "/redoc", "/openapi.json")]

    assert [response.status_code for response in responses] == [404, 404, 404]


def test_settings_repr_does_not_expose_flags(settings):
    rendered = repr(settings)
    assert all(flag not in rendered for flag in ("test-one", "test-two", "test-three"))
