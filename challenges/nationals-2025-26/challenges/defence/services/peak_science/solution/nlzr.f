      INTEGER SP, PI
      REAL ENERGY_NUMBER, DEVIATION_NUMBER, MEAN_ENERGY_NUMBER_PER_CELL
      LOGICAL IS_ENERGY_NUMBER_DANGEROUS,DERIVATIVE_CORRECT
      REAL DIFF

      CHARACTER*64 FN
      CHARACTER*64 FF

      READ (*, *) ENERGY_NUMBER
      READ (*, *) DEVIATION_NUMBER
      READ (*, *) SP
      READ (*, *) PI

      MEAN_ENERGY_NUMBER_PER_CELL = ENERGY_NUMBER / SP
C MODIFICATION FOR FLAG 2
      IS_ENERGY_NUMBER_DANGEROUS = (MEAN_ENERGY_NUMBER_PER_CELL > 30.0)
     +.AND. (DEVIATION_NUMBER > 50.0)
C END OF MODIFICATION FOR FLAG 2
      PRINT*,MEAN_ENERGY_NUMBER_PER_CELL
