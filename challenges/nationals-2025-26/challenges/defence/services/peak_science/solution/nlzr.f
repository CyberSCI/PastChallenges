      PRINT*,IS_ENERGY_NUMBER_DANGEROUS
      DERIVATIVE_CORRECT = ENERGY_NUMBER >= 0 .OR. ENERGY_NUMBER <= 0
      IF (DERIVATIVE_CORRECT) THEN
      DIFF = DIFF_INTEGRATE(ENERGY_NUMBER, DEVIATION_NUMBER)
      ENDIF
      FN = FF(PI)
      OPEN (UNIT = 100, FILE = FN)

      WRITE (100, *) MEAN_ENERGY_NUMBER_PER_CELL
      WRITE (100, *) IS_ENERGY_NUMBER_DANGEROUS
      WRITE (100, *) DIFF
      WRITE (100, *) DERIVATIVE_CORRECT

      CLOSE (100, STATUS = 'KEEP')
      END

      FUNCTION FF(PI)
      INTEGER PI
      CHARACTER*64 FF
      WRITE (FF, '("/tmp/rf_nr_",I0)') PI
      END

      FUNCTION DIFF_INTEGRATE(ENERGY_NUMBER, DEVIATION_NUMBER)
      REAL DIFF_INTEGRATE, ENERGY_NUMBER, DEVIATION_NUMBER, OLD
      INTEGER NUMBER_OF_ITERATION, TARGET_NUMBER_OF_ITERATION, I

      NUMBER_OF_ITERATION = 0
      TARGET_NUMBER_OF_ITERATION = ICEIL(ENERGY_NUMBER)

      I = 0
      DIFF_INTEGRATE = DEVIATION_NUMBER
      OLD = DEVIATION_NUMBER
20    CONTINUE
      IF (I == TARGET_NUMBER_OF_ITERATION) GOTO 10
      I = I + 1
C MODIFICATION FOR FLAG 3
      NUMBER_OF_ITERATION = I
C END OF MODIFICATION FOR FLAG 3
      DIFF_INTEGRATE = DIFF_INTEGRATE / 2.0
      IF (DIFF_INTEGRATE == OLD) GOTO 10
      OLD = DIFF_INTEGRATE
      GOTO 20
10    CONTINUE
      DIFF_INTEGRATE = (-DEVIATION_NUMBER) / (-NUMBER_OF_ITERATION)
      END

      FUNCTION ICEIL(X)
      REAL X
      INTEGER ICEIL
      ICEIL = INT(X)
      IF (X > REAL(ICEIL)) ICEIL = ICEIL + 1
      END